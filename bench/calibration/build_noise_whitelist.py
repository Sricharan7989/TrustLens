"""Dev C: turn benign install/import traces (QUT-DV25 or OSPtrack) into a noise whitelist for the normalizer.

  python bench/calibration/build_noise_whitelist.py --csv data/qut/<file>.csv --label-col Label --benign-value 0 \
      --cols Files Sockets Commands DNS --min-prevalence 0.02 --out bench/calibration/noise_whitelist.yaml
UNVERIFIED: the real QUT-DV25 / OSPtrack column names and cell formats were never inspected (we only read repo build scripts).
STEP 1 for Dev C: head -c 2000 the CSV, fix --cols / parse_cell(), then run. Never claim these datasets train anything.
A token is whitelisted when it occurs in >= min-prevalence of BENIGN rows AND in < 1/4 of that prevalence of malicious rows (rare-in-malware noise only).
Output schema = trustlens/engine/noise_whitelist.yaml rules: {capability, path_glob|host_glob|env_glob, reason, source, benign_prevalence}.
"""
from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

CAP_OF = {"files": ("fs_read_sensitive", "path_glob"), "sockets": ("network", "host_glob"), "dns": ("network", "host_glob"), "commands": ("subprocess", "path_glob")}


def parse_cell(cell: str) -> set[str]:
    return {t.strip() for t in re.split(r"[;\n|]|\s{2,}|,\s*(?=[/~\w])", cell or "") if t.strip()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", required=True)
    ap.add_argument("--label-col", default="Label")
    ap.add_argument("--benign-value", default="0")
    ap.add_argument("--cols", nargs="+", default=["Files", "Sockets", "Commands", "DNS"])
    ap.add_argument("--min-prevalence", type=float, default=0.02)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default="bench/calibration/noise_whitelist.yaml")
    a = ap.parse_args()
    csv.field_size_limit(sys.maxsize)
    ben, mal = {c: Counter() for c in a.cols}, {c: Counter() for c in a.cols}
    nb = nm = 0
    with open(a.csv, newline="", encoding="utf-8", errors="replace") as fh:
        for i, row in enumerate(csv.DictReader(fh)):
            if a.limit and i >= a.limit:
                break
            is_ben = str(row[a.label_col]) == a.benign_value
            nb, nm = nb + is_ben, nm + (not is_ben)
            for c in a.cols:
                (ben if is_ben else mal)[c].update(parse_cell(row.get(c, "")))
    rules = []
    for c in a.cols:
        cap, key = CAP_OF.get(c.lower().split("_")[-1], (None, None))
        if not cap:
            continue
        for tok, k in ben[c].most_common(500):
            pb = k / max(nb, 1)
            pm = mal[c][tok] / max(nm, 1)
            if pb >= a.min_prevalence and pm < pb / 4:
                rules.append({"capability": cap, key: tok, "reason": f"benign prevalence {pb:.1%} vs malicious {pm:.1%}", "source": f"{Path(a.csv).name}:{c}", "benign_prevalence": round(pb, 4)})
    Path(a.out).write_text("# generated by build_noise_whitelist.py (calibration only, not training)\n" + yaml.safe_dump({"rules": rules}, sort_keys=False))
    print(f"{nb} benign / {nm} malicious rows -> {len(rules)} whitelist rules -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
