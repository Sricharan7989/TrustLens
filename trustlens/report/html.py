"""Dev D: self-contained HTML report (no JS, no external assets). STUB-LEVEL v0 - already renders verdict, evidence chains,
timeline and coverage. TODO(Dev D): claims-vs-behaviour two-column hero view, env-differential side-by-side, polish, print CSS.
All dynamic text MUST go through esc() (package READMEs and decoded payloads are attacker-controlled).
"""
from __future__ import annotations

from html import escape as esc

CSS = """body{font:14px system-ui,sans-serif;max-width:1000px;margin:2em auto;color:#222}h1{margin-bottom:0}.badge{display:inline-block;padding:.2em .7em;border-radius:4px;color:#fff;font-weight:700}
.PASS{background:#2e7d32}.REVIEW{background:#ef6c00}.BLOCK{background:#c62828}table{border-collapse:collapse;width:100%;margin:.5em 0}td,th{border:1px solid #ddd;padding:4px 8px;text-align:left;vertical-align:top}
th{background:#f4f4f4}code{background:#f4f4f4;padding:0 3px}.f{border-left:4px solid #999;padding:.3em .8em;margin:.6em 0;background:#fafafa}.critical,.high{border-color:#c62828}.medium{border-color:#ef6c00}
.ev-attempted{color:#555}.ev-blocked{color:#ef6c00}.ev-succeeded{color:#c62828;font-weight:700}small{color:#666}"""


def render_html(verdict: dict, fingerprint: dict | None = None, claims: dict | None = None) -> str:
    p, cov = verdict["package"], verdict["coverage"]
    h = [f"<!doctype html><meta charset=utf-8><title>TrustLens: {esc(p['name'])}</title><style>{CSS}</style>",
         f"<h1>{esc(p['name'])} {esc(p['version'])}</h1><p><span class='badge {esc(verdict['action'])}'>{esc(verdict['action'])}</span> "
         f"<b>{esc(verdict['verdict'])}</b> &middot; score {verdict['score']} &middot; confidence {esc(verdict['confidence'])}</p><p>{esc(verdict['summary'])}</p>"]
    if claims:
        h.append("<h2>What the package claims</h2><ul>" + "".join(f"<li><code>{esc(i['intent'])}</code>: &ldquo;{esc(i['quote'])}&rdquo; <small>({esc(i['source'])})</small></li>" for i in claims["intents"])
                 + ("<li><i>no recognisable claim: no discount applied</i></li>" if claims["unknown_intent"] else "") + "</ul>")
    h.append("<h2>Findings (claim &rarr; event &rarr; evidence)</h2>")
    for f in verdict["findings"] or []:
        ev = "".join(f"<tr><td>{esc(e['event_id'])}</td><td>{esc(e['phase'])}/{esc(e.get('profile', ''))}</td><td>{esc(str(e.get('file')))}:{esc(str(e.get('line')))}</td>"
                     f"<td class='ev-{esc(e['outcome'])}'>{esc(e['outcome'])}</td></tr>" for e in f["evidence"])
        h.append(f"<div class='f {esc(f['severity'])}'><b>[{esc(f['severity'])}] {esc(f['title'])}</b> <small>rule {esc(f['rule'])}, signal {esc(f['signal_class'])}"
                 f"{', env-differential' if f['env_differential'] else ''}{', canary' if f['canary_hit'] else ''}</small><p>{esc(f['explanation'])}</p>"
                 f"<table><tr><th>event</th><th>phase/profile</th><th>file:line</th><th>outcome</th></tr>{ev}</table></div>")
    if not verdict["findings"]:
        h.append("<p>No findings.</p>")
    if fingerprint:
        h.append("<h2>Behaviour timeline</h2><table><tr><th>#</th><th>profile</th><th>phase</th><th>capability</th><th>detail</th><th>outcome</th><th>canary</th></tr>")
        for e in fingerprint["events"]:
            d = e["detail"]
            txt = str(d.get("path") or d.get("name") or d.get("dest") or d.get("host") or d.get("url") or d.get("decoded_snippet") or d)[:100]
            h.append(f"<tr><td>{e['seq']}</td><td>{esc(e['profile'])}</td><td>{esc(e['phase'])}</td><td>{esc(e['capability'])}</td><td><code>{esc(txt)}</code></td>"
                     f"<td class='ev-{esc(e['outcome'])}'>{esc(e['outcome'])}</td><td>{esc(','.join(e['canary_ids']))}</td></tr>")
        h.append("</table>")
    h.append("<h2>Coverage: what we did and did not observe</h2><ul>"
             f"<li>phases: {esc(', '.join(cov['phases_run']))}; profiles: {esc(', '.join(cov['profiles_run']))}; triggers: {esc(', '.join(cov['triggers_run']))}</li>"
             f"<li>callables exercised: {cov['callables_exercised']}/{cov['callables_total']}; install completed: {cov['install_completed']}; network: {esc(cov['network'])}</li>"
             + "".join(f"<li><i>not observed:</i> {esc(x)}</li>" for x in cov["not_observed"]) + "</ul>")
    if fingerprint and fingerprint["run"].get("stub"):
        h.append("<p><small>Events replayed from a recorded run (fixture mode), not executed just now.</small></p>")
    h.append("<p><small>Generated by TrustLens AI. Rule-based, offline. Verdicts describe observed behaviour within the stated coverage; they are not proof of safety.</small></p>")
    return "".join(h)
